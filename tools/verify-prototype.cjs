// Browser-only UI prototype checks. No model calls or database access.
const {chromium} = require('playwright');
const fs = require('fs');
const path = require('path');
const {pathToFileURL} = require('url');
(async()=>{
  const root=path.resolve(__dirname,'..'),output=path.join(root,'reports/validation');
  const checks=[],errors=[],external=[];
  const check=(condition,label)=>{if(!condition)throw Error(label);checks.push(label);};
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1080},reducedMotion:'reduce',acceptDownloads:true});
    const page=await context.newPage();
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
    await page.goto(pathToFileURL(path.join(root,'docs/prototipo-plataforma.html')).href);
    await page.evaluate(()=>localStorage.clear());await page.reload();
    check(await page.getByRole('heading',{name:'Entidades e relações',exact:true}).isVisible(),'Graph extraction editor is initial screen');
    check((await page.locator('.demo-banner').innerText()).includes('fictícios'),'Persistent simulation disclosure');
    await page.screenshot({path:path.join(output,'prototype-editor.png')});
    const prompt=page.locator('#graphPrompt');await prompt.fill('Extraia relações com papéis e evidência. {{passages}}');
    check((await page.locator('#version-label').textContent()).includes('Rascunho'),'Prompt edits mark draft');
    await page.getByRole('button',{name:'Ver prévia',exact:true}).click();
    check((await page.locator('#dialog-body').textContent()).includes('Associação Aurora'),'Prompt preview substitutes demonstration passage');
    await page.keyboard.press('Escape');check(!(await page.locator('#dialog').isVisible()),'Escape closes dialog');
    await page.getByRole('button',{name:'Salvar versão',exact:true}).click();
    check((await page.locator('#version-label').textContent()).includes('v3'),'New version saved');
    await page.reload();check((await page.locator('#graphPrompt').inputValue()).startsWith('Extraia relações'),'Local persistence after reload');
    const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('indexing-methods-ui-prototype-v1')));
    check(stored.versions[1].config.graphPrompt!==stored.config.graphPrompt,'Earlier saved version remains unchanged');
    await page.getByRole('button',{name:'Duplicar',exact:true}).click();await page.locator('#duplicate-name').fill('Teste de interface');
    await page.getByRole('button',{name:'Criar rascunho',exact:true}).click();
    check((await page.locator('#experiment-title').textContent())==='Teste de interface','Configuration duplication');
    await page.getByRole('button',{name:'Recortes e pacotes',exact:true}).click();
    await page.getByRole('spinbutton',{name:'Sobreposição',exact:true}).fill('2000');
    check((await page.locator('#config-error').textContent()).includes('menor que o recorte'),'Invalid overlap is explained');
    await page.getByRole('spinbutton',{name:'Sobreposição',exact:true}).fill('200');
    for(const name of ['Leitura do PDF','Resumos','Embeddings','Recuperação','Extração JSON','Verificação']){
      await page.getByRole('button',{name,exact:true}).click();
      check(await page.getByRole('heading',{name,exact:true}).isVisible(),`Stage opens: ${name}`);
    }
    await page.getByRole('button',{name:'Matriz de testes',exact:true}).click();
    check((await page.locator('#matrix-configs').textContent())==='24','Default matrix has 24 configurations');
    check((await page.locator('#matrix-runs').textContent())==='144','Default matrix has 144 document runs');
    await page.locator('input[data-axis="topks"][value="12"]').uncheck();
    check((await page.locator('#matrix-runs').textContent())==='96','Changing one axis recomputes runs');
    await page.locator('input[data-axis="documents"][value="adpf54"]').uncheck();
    await page.locator('input[data-axis="documents"][value="dom-casmurro"]').uncheck();
    check(await page.locator('#build-batch').isDisabled(),'Empty dataset blocks simulation');
    await page.getByRole('button',{name:'Restaurar matriz',exact:true}).click();
    await page.screenshot({path:path.join(output,'prototype-matrix.png')});
    await page.getByRole('button',{name:'Ver combinações',exact:true}).click();
    check(await page.locator('#dialog tbody tr').count()===24,'Matrix preview lists all combinations');
    const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Exportar JSON',exact:true}).click();
    const download=await downloadPromise;const data=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    check(data.prototype===true&&data.counts.runs===144,'Export identified as prototype with matching counts');
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Simular bateria',exact:true}).click();
    check(await page.locator('#run-table-wrap tbody tr').count()===10,'Simulation table paginated');
    check(await page.getByRole('columnheader',{name:'Tempo total',exact:true}).isVisible(),'Runs expose total time without opening a dialog');
    await page.getByRole('button',{name:'Inspecionar',exact:true}).nth(1).click();
    check((await page.locator('#run-time-total').textContent())==='—','Queued run has unknown duration, not zero');
    check((await page.locator('#run-stage-times').textContent()).includes('Aguardando início'),'Pending stages are clearly waiting');
    await page.keyboard.press('Escape');
    await page.getByRole('button',{name:'Avançar simulação',exact:true}).click();
    check((await page.locator('.run-summary').textContent()).includes('36 / 144'),'Manual simulation progresses one quarter');
    await page.getByRole('button',{name:'Pausar',exact:true}).click();
    check(await page.getByRole('button',{name:'Avançar simulação',exact:true}).isDisabled(),'Paused simulation cannot advance');
    await page.getByRole('button',{name:'Retomar',exact:true}).click();
    await page.locator('#run-search').fill('NO-MATCH');
    check(await page.getByRole('heading',{name:'Nenhuma execução encontrada'}).isVisible(),'Empty search state');
    await page.locator('#run-search').fill('');
    await page.getByRole('button',{name:'Inspecionar',exact:true}).first().click();
    check((await page.locator('#dialog-body').textContent()).includes('Nenhuma medição real'),'Run detail discloses simulated evidence');
    check(await page.locator('#run-stage-times [data-stage-time]').count()===13,'Run detail exposes every stage including queue and OCR');
    const runTime=await page.locator('#run-stage-times [data-stage-time]').evaluateAll(rows=>rows.reduce((sum,row)=>sum+Number(row.dataset.seconds||0),0));
    check(runTime===107&&Number(await page.locator('#run-time-total').getAttribute('data-seconds'))===runTime,'Run stage durations reconcile with total including queue and evaluation');
    check((await page.locator('#run-stage-times [data-stage-time="entities"]').textContent()).includes('Construção anterior: 46 s'),'Cached stage shows historical duration separately');
    await page.screenshot({path:path.join(output,'prototype-run-times.png')});
    await page.keyboard.press('Escape');
    await page.screenshot({path:path.join(output,'prototype-runs.png')});
    await page.getByRole('button',{name:'Cancelar',exact:true}).click();
    check((await page.locator('.cardhead').textContent()).includes('Cancelada'),'Cancel preserves completed runs and stops pending');
    await page.getByRole('button',{name:'Comparação',exact:true}).click();
    check((await page.locator('main .warning').textContent()).includes('fictícios'),'Comparison clearly fictitious');
    check(await page.getByRole('heading',{name:'Tempos por etapa'}).isVisible(),'Stage timing is prominent in comparison');
    check(await page.locator('#stage-times [data-stage-time]').count()===13,'Comparison includes all timing stages');
    const totals=await page.locator('#stage-times [data-stage-time]').evaluateAll(rows=>rows.reduce((sum,row)=>({a:sum.a+Number(row.dataset.reference||0),b:sum.b+Number(row.dataset.candidate||0)}),{a:0,b:0}));
    check(totals.a===144&&totals.b===217,'Full pipeline stage times reconcile independently for both versions');
    check((await page.locator('#timing-index').getAttribute('data-seconds'))==='110','Index duration includes graph and both storage writes');
    check((await page.locator('#timing-extract').getAttribute('data-seconds'))==='93','Extraction includes retrieval, JSON and verification');
    check((await page.locator('#stage-times [data-stage-time="ocr"]').textContent()).includes('Não necessário'),'Unused OCR is not reported as a zero-duration measurement');
    await page.locator('#tempos').screenshot({path:path.join(output,'prototype-stage-times.png')});
    await page.locator('#timing-mode').selectOption('reuse');
    check((await page.locator('#timing-total').getAttribute('data-seconds'))==='107','Reused index construction is excluded from current total');
    check((await page.locator('#timing-index').getAttribute('data-seconds'))==='0','Cached indexing clearly has no new processing');
    check((await page.locator('#stage-times [data-stage-time="entities"]').textContent()).includes('construção anterior 46 s'),'Comparison preserves historical graph construction time');
    await page.locator('#compare-document').selectOption('dom-casmurro');
    check((await page.locator('.compare-table').textContent()).includes('81,3%'),'Document changes illustrative results');
    check((await page.locator('#timing-total').getAttribute('data-seconds'))==='85','Changing document updates duration values');
    await page.locator('#compare-baseline').selectOption('graph');
    check((await page.locator('#stage-times [data-stage-time="json"] .timing-delta').textContent())==='0 s','Same version yields zero timing delta');
    await page.locator('#compare-baseline').selectOption('hybrid');
    await page.locator('#timing-mode').selectOption('full');
    await page.getByRole('button',{name:'Ver evidências',exact:true}).first().click();
    check((await page.locator('#dialog-body').textContent()).includes('não é uma resposta')||(await page.locator('#dialog-body').textContent()).includes('Não é uma resposta'),'Field details label fictional content');
    await page.screenshot({path:path.join(output,'prototype-evidence.png')});
    await page.keyboard.press('Escape');
    await page.locator('#compare-document').selectOption('adpf54');
    await page.screenshot({path:path.join(output,'prototype-comparison.png')});
    await page.locator('.navbutton[data-page="grafo"]').click();
    await page.getByRole('button',{name:'Participação posterior',exact:true}).focus();await page.keyboard.press('Enter');
    check((await page.locator('#graph-detail').textContent()).includes('momento')||(await page.locator('#graph-detail').textContent()).includes('depois'),'Graph keyboard interaction');
    await page.screenshot({path:path.join(output,'prototype-graph.png')});
    await page.locator('.navbutton[data-page="biblioteca"]').click();
    check(await page.locator('.doccard').count()===2,'Both document cards visible');
    await page.locator('.navbutton[data-page="prompts"]').click();
    check(await page.locator('.prompt-row').count()===4,'Separate prompts for four stages');
    await page.getByRole('button',{name:'Ver versões salvas',exact:true}).click();
    check(await page.locator('.version-row').count()===3,'Saved version list');await page.keyboard.press('Escape');
    const widths=[];
    for(const width of [390,768,1280,1440]){
      await page.setViewportSize({width,height:900});
      // Use route action directly in the page only to select pages for layout inspection.
      for(const section of ['experimentos','biblioteca','prompts','grafo']){
        await page.locator(`.navbutton[data-page="${section}"]`).evaluate(e=>e.click());
        const measure=await page.evaluate(()=>({viewport:innerWidth,body:document.body.scrollWidth,document:document.documentElement.scrollWidth}));
        widths.push({page:section,...measure});check(measure.body<=width&&measure.document<=width,`No page overflow: ${section} at ${width}`);
      }
      await page.locator('.navbutton[data-page="experimentos"]').evaluate(e=>e.click());
      for(const [section,tabId] of [['Configuração','config'],['Matriz de testes','matrix'],['Execuções','runs'],['Comparação','compare']]){
        await page.locator(`.tabs [data-action="tab"][data-tab="${tabId}"]`).click();
        const size=await page.evaluate(()=>document.documentElement.scrollWidth);
        check(size<=width,`No tab overflow: ${section} at ${width}`);
      }
    }
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Configuração',exact:true}).click();
    await page.getByRole('button',{name:'Entidades e relações',exact:true}).click();
    await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:path.join(output,'prototype-mobile.png')});
    await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
    check(await page.locator('.sidebar.open').isVisible(),'Mobile navigation opens');
    await page.locator('.navbutton[data-page="biblioteca"]').click();
    check(await page.locator('.sidebar.open').count()===0,'Mobile navigation closes after selection');
    await page.goto(pathToFileURL(path.join(root,'docs/prototipo-plataforma.html')).href+'#tempos');
    check(await page.getByRole('heading',{name:'Tempos por etapa'}).isVisible(),'Direct time link opens comparison and scrolls to timing section');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Direct timing view fits mobile viewport');
    await page.screenshot({path:path.join(output,'prototype-times-mobile.png')});
    check(errors.length===0,'No JavaScript errors');check(external.length===0,'No external network requests');
    fs.writeFileSync(path.join(output,'prototype-checks.json'),JSON.stringify({status:'passed',scope:'Offline UI prototype; simulated runs and metrics only',checks,widths,javascript_errors:errors,external_requests:external,checked_at:new Date().toISOString()},null,2));
    console.log(JSON.stringify({status:'passed',checks:checks.length,javascript_errors:errors,external_requests:external}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
